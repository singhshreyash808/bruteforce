/**
 * Look up the canonical state name, handling aliases
 */
export function resolveStateName(rawName) {
  if (!rawName) return null;
  const normalized = normalizeName(rawName);
  // Direct match
  for (const key of Object.keys(stateGeo)) {
    if (normalizeName(key) === normalized) return key;
  }
  // Alias match
  const alias = stateAliases[normalized];
  if (alias) return alias;
  return null; // Not found
}

/**
 * Get state geographic data (center + bounds)
 * Returns { lat, lng, zoom, bounds } or null
 */
export function getStateGeo(stateName) {
  const canonical = resolveStateName(stateName);
  if (!canonical) return null;
  return stateGeo[canonical] || null;
}

/**
 * Get district geographic data (center + bounds)
 * MUST be called with both state and district to prevent cross-state collision
 * Returns { lat, lng, zoom, bounds } or null
 */
export function getDistrictGeo(stateName, districtName) {
  const canonical = resolveStateName(stateName);
  if (!canonical) return null;
  const districtMap = districtGeo[canonical];
  if (!districtMap) return null;
  const normalizedDistrict = normalizeName(districtName);
  // Try exact match first
  if (districtMap[districtName]) return districtMap[districtName];
  // Try case-insensitive match
  for (const key of Object.keys(districtMap)) {
    if (normalizeName(key) === normalizedDistrict) return districtMap[key];
  }
  return null;
}

