def normalize_name(s: str) -> str:
    """Normalizes string: lowercase, strips parenthesized parts, remove non-alphanumeric."""
    if not s:
        return ""
    # Strip (parenthesized) parts
    s = re.sub(r'\(.*?\)', '', s)
    return "".join(c for c in s.lower() if c.isalnum())

def get_district_coords(state: str, district: str):
    """
    Returns verified [lat, lng] for a district within a state.
    Uses state+district composite key to prevent cross-state collision.
    Supports normalized name matching for parenthetical variants (e.g. 'Bengaluru (Bangalore) Urban').
    Falls back to state center if district not found.
    Validates that lat is in [-90,90] and lng is in [-180,180].
    Never returns random coordinates.
    """
    # 1. Try exact state match
    state_districts = DISTRICT_COORDS.get(state)
    
    # If not found, try normalized state lookup
    if not state_districts:
        norm_state = normalize_name(state)
        for s_key, s_val in DISTRICT_COORDS.items():
            if normalize_name(s_key) == norm_state:
                state_districts = s_val
                break

    if state_districts:
        # Direct lookup
        coords = state_districts.get(district)
        if coords:
            lat, lng = coords
            if -90 <= lat <= 90 and -180 <= lng <= 180:
                return lat, lng

        # Normalized lookup (handles "Bengaluru (Bangalore) Urban" vs "Bengaluru Urban")
        norm_dist = normalize_name(district)
        for d_key, d_coords in state_districts.items():
            if normalize_name(d_key) == norm_dist:
                lat, lng = d_coords
                if -90 <= lat <= 90 and -180 <= lng <= 180:
                    return lat, lng

    # Try state center
    state_center = STATE_CENTERS.get(state)
    if not state_center:
        norm_state = normalize_name(state)
        for s_key, s_coords in STATE_CENTERS.items():
            if normalize_name(s_key) == norm_state:
                state_center = s_coords
                break

    if state_center:
        lat, lng = state_center
        return lat, lng

    # Final fallback: geographic center of India
    return 22.5937, 80.9629
